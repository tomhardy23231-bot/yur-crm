// Модель печатного/выгружаемого отчёта (2026-08-03).
//
// ЗАЧЕМ ОБЩАЯ МОДЕЛЬ. Отчётов кассы семь, форматов вывода три (экран, Excel,
// PDF). Писать 7×3 отдельных верстальщиков — гарантированный расход цифр между
// форматами: в Excel одна сумма, в PDF другая. Поэтому отчёт описывается ОДИН
// раз как «шапка + колонки + строки + итоги», а рендереры (lib/reports/export/
// xlsx.ts и печатная страница) только раскладывают это по своему формату.
//
// Значения в ячейках — уже посчитанные числа и готовые строки. Никакой
// бизнес-логики в рендерерах: они не суммируют и не пересчитывают, иначе
// правило «источник правды один» сломается.

/** Тип ячейки — задаёт выравнивание и числовой формат в Excel. */
export type ReportCellType = 'text' | 'money' | 'number' | 'percent' | 'date';

export type ReportColumn = {
  /** Ключ ячейки в ReportRow.cells. */
  key: string;
  label: string;
  /** По умолчанию 'text'. */
  type?: ReportCellType;
  /** Ширина колонки в Excel, в символах. */
  width?: number;
};

/** null — пустая ячейка (не ноль: «нет данных» и «ноль» это разное). */
export type ReportCell = string | number | null;

export type ReportRow = {
  cells: Record<string, ReportCell>;
  /** Выделить строку жирным (подытог, «Прочее», строка группы). */
  emphasis?: boolean;
  /** Ссылка на карточку сущности — используется только на экране. */
  href?: string;
};

export type ReportDoc = {
  /** «Оборотно-сальдова відомість». */
  title: string;
  /** Готовая подпись периода: «Липень 2026», «01.03.2026 — 15.04.2026». */
  periodLabel: string;
  /** Шапка компании-исполнителя из org_requisites; null — не показывать. */
  org?: { name: string; edrpou: string | null } | null;
  columns: ReportColumn[];
  rows: ReportRow[];
  /** Строка «Разом»; ключи те же, что у колонок. */
  totals?: Record<string, ReportCell> | null;
  /**
   * Сноски под таблицей. Сюда уходит пояснение про два источника денег
   * (касса против оплат по делам) — без него разные суммы в соседних
   * вкладках читаются как ошибка расчёта.
   */
  notes?: string[];
  /** Момент формирования, 'DD.MM.YYYY HH:mm' в киевском времени. */
  generatedAt: string;
  /** Кто выгрузил — для бумажной копии. */
  generatedBy?: string | null;
  /** Базовое имя файла без расширения: 'oborotka-2026-07'. */
  fileBase: string;
};

/** Пустой ли отчёт — общий признак для «нет данных» во всех форматах. */
export function isEmptyReport(doc: ReportDoc): boolean {
  return doc.rows.length === 0;
}
